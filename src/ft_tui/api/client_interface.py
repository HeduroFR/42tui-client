"""Provider contract for the centralized 42TUI API."""

from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path
from typing import Protocol


@dataclass(frozen=True, slots=True)
class CursusSnapshot:
    """Cursus data supplied by the centralized API."""

    id: int
    name: str
    begin_at: datetime | None = None
    end_at: datetime | None = None


class ProjectProvider(Protocol):
    """Authenticated catalog reader. No browser credentials enter this interface."""
    def get_social(self) -> dict: ...
    def get_poke_neighbours(self) -> list[dict]: ...
    def social_action(self, draft: dict) -> dict: ...
    def event_stream(self, stop): ...
    def list_cursuses(self) -> list[CursusSnapshot]: ...
    def list_campuses(self) -> list[dict]: ...
    def get_profile(self) -> dict: ...
    def get_cluster_map(self) -> dict: ...
    def get_cluster_portrait(self, hostname: str) -> dict: ...
    def get_cluster_issues(self, hostname: str, *, include_resolved: bool = False, cursor: str | None = None) -> dict: ...
    def get_cluster_issue_options(self) -> dict: ...
    def submit_cluster_issue(self, hostname: str, draft: dict, idempotency_key: str) -> dict: ...
    def search_students(self, query: str, *, limit=20, exclude_ids=()) -> dict: ...
    def list_friend_directory_page(self, campus_id: int, page: int = 1) -> dict: ...
    def get_friend_core(self, login: str, cursus_id: int, *, refresh=False, user_id=None) -> dict: ...
    def get_friend(self, login: str, cursus_id: int, *, refresh=False, user_id=None) -> dict: ...
    def get_goals(self, cursus_id: int, account_id: str) -> dict: ...
    def list_catalog_page(self, scope, **filters) -> dict: ...
    def get_catalog_project(self, project_id: int, scope, snapshot_id=None) -> dict: ...
    def list_branches(self, scope, track: str, cursor=None) -> dict: ...
    def get_branch(self, scope, track: str, branch_id: str, snapshot_id=None) -> dict: ...
    def get_account_projects(self, cursus_id: int, cursor=None) -> dict: ...
    def get_project_activity(self, project_id: int, scope, account_id: str, *, refresh=False) -> dict: ...
    def get_team_evaluations(self, project_id: int, team_id: int, scope, account_id: str, *, refresh=False) -> dict: ...
    def get_project_team(self, project_id: int, scope, account_id: str) -> dict: ...
    def change_project_team(self, project_id: int, scope, account_id: str, action: dict, idempotency_key: str) -> dict: ...
    def get_project_registration(self, project_id: int, scope, account_id: str) -> dict: ...
    def refresh_project_registration(self, project_id: int, scope, account_id: str) -> dict: ...
    def register_project(self, project_id: int, scope, account_id: str, idempotency_key: str) -> dict: ...
    def get_curriculum(self, scope) -> dict: ...
    def get_subject_reference_sha256(self, slug: str) -> str | None: ...
    def download_subject_pdf(self, slug: str, destination: Path) -> bool: ...
