"""Capabilities needed to load and retain account-scoped friend observations."""
from typing import Protocol

class FriendsRepository(Protocol):
    def configured_cursus(self, selector=None) -> int | None: ...
    def memberships(self, account: str, *, origin: str = '') -> list: ...
    def cached(self, account: str, cursus: int, *, origin: str = '') -> dict: ...
    def save(self, account: str, value: dict, *, origin: str = '') -> None: ...
    def forget(self, account: str, cursus: int, login: str, *, origin: str = '') -> None: ...

class FriendsReader(Protocol):
    def summary(self, provider, login: str, cursus: int, **options) -> dict: ...
    def detail(self, provider, login: str, cursus: int, **options) -> dict: ...
    def batch(self, provider, logins: list[str], cursus: int) -> list[dict]: ...
    def search(self, provider, query: str, **options) -> dict: ...
