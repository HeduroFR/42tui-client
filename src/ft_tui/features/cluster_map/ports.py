"""Provider and local persistence contracts for the cluster feature."""
from typing import Protocol


class ClusterReader(Protocol):
    def get_cluster_map(self) -> dict: ...
    def get_cluster_portrait(self,hostname: str) -> dict: ...
    def get_cluster_issues(self,hostname: str,*,include_resolved=False,cursor=None) -> dict: ...
    def get_cluster_issue_options(self) -> dict: ...
    def get_friend(self,login: str,cursus,**options) -> dict: ...


class ClusterReporter(Protocol):
    def submit_cluster_issue(self,hostname: str,draft: dict,idempotency_key: str) -> dict: ...


class ClusterRepository(Protocol):
    def memberships(self,account,*,origin=''): ...
    def configured_cursus(self): ...
    def portrait_directory(self,account,origin): ...
