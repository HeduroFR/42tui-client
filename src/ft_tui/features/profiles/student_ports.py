"""Provider capabilities consumed by read-only student profiles."""
from typing import Protocol


class StudentProfileReader(Protocol):
    def search_students(self, query, *, limit=20): ...
    def get_student_profile(self, user_id, *, refresh=False): ...
    def get_student_attendance(self, user_id, *, refresh=False): ...
    def get_student_goals(self, user_id, cursus_id): ...
    def get_friend(self, login, cursus_id, *, refresh=False, user_id=None): ...
