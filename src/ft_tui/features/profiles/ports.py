"""Capabilities consumed by profile reads and goal synchronization."""
from typing import Protocol


class ProfileRepository(Protocol):
    def load_profile(self, client: object) -> dict: ...
    def save_profile(self, client: object, profile: dict) -> None: ...
    def load_goals(self, account: str, cursus: int) -> dict: ...
    def save_goals(self, account: str, cursus: int, value: dict) -> None: ...


class CursusSelection(Protocol):
    def configured_cursus(self) -> int | None: ...


class GoalsReader(Protocol):
    def get_goals(self, cursus: int, account: str) -> dict: ...
