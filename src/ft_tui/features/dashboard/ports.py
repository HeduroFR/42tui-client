"""Read-only local worklog projections used to compose the dashboard."""
from datetime import date, datetime
from typing import Protocol


class DashboardReader(Protocol):
    def tracked(self, project_id: int) -> float: ...
    def recent_notes(self) -> list[tuple]: ...
    def daily_heartbeats_since(self, start: datetime) -> list[tuple[date, float]]: ...
    def activity(self) -> tuple[dict, tuple | None]: ...
