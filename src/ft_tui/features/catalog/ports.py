"""I/O capabilities used by catalog operations, without UI or ORM types."""
from typing import Protocol
from .models import CatalogScope


class CatalogReader(Protocol):
    def get_curriculum(self, scope: CatalogScope) -> dict: ...
    def get_account_projects(self, cursus_id: int, cursor: str | None = None) -> dict: ...
    def list_catalog_page(self, scope: CatalogScope, **query) -> dict: ...
    def list_branches(self, scope: CatalogScope, track: str, cursor: str | None = None) -> dict: ...
    def get_catalog_project(self, project_id: int, scope: CatalogScope, snapshot: str | None) -> dict: ...


class CatalogRepository(Protocol):
    def configured_cursus(self) -> int | None: ...
    def preference(self, key: str) -> str | None: ...
    def save_personal(self, account: str, scope: CatalogScope, curriculum: dict, attempts: list) -> dict: ...
    def cached(self, scope: CatalogScope) -> dict | None: ...
    def save_branches(self, scope: CatalogScope, track: str, page: dict) -> None: ...
    def publish(self, scope: CatalogScope, pages: list, snapshot: str, project_ids: set[int]) -> None: ...
    def detail(self, scope: CatalogScope, project_id: int, snapshot: str | None) -> dict | None: ...
    def save_detail(self, scope: CatalogScope, detail: dict) -> bool: ...
