"""Provider capabilities for registration and team workflows."""
from typing import Protocol

class RegistrationProvider(Protocol):
    def get_project_registration(self, project_id, scope, account_id) -> dict: ...
    def refresh_project_registration(self, project_id, scope, account_id) -> dict: ...
    def register_project(self, project_id, scope, account_id, key) -> dict: ...

class TeamProvider(Protocol):
    def get_project_team(self, project_id, scope, account_id) -> dict: ...
    def change_project_team(self, project_id, scope, account_id, action, key) -> dict: ...
