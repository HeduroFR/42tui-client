"""Subject provider, project metadata and local-file capabilities."""
from typing import Protocol


class SubjectProvider(Protocol):
    def get_subject_reference_sha256(self,slug: str) -> str | None: ...
    def download_subject_pdf(self,slug,destination) -> bool: ...


class SubjectRepository(Protocol):
    def subjects(self): ...
    def save(self,project_id,local_path,path,digest,reference,checked) -> bool: ...


class SubjectStorage(Protocol):
    def root(self,path): ...
    def subject(self,root): ...
    def regular(self,path) -> bool: ...
    def symlink(self,path) -> bool: ...
    def ensure_ignore(self,root): ...
    def synchronize(self,slug,path,downloader,reference,*,current): ...
    def inspect(self,local_path,subject_path): ...
    def viewer(self,name): ...
    def run_tdf(self,executable,path): ...
    def open_system(self,path): ...
