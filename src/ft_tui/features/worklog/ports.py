"""Local worklog persistence capabilities."""
from typing import Protocol
from .models import Note,TimerSummary,TimerOutcome,HeartbeatOutcome

class WorklogRepository(Protocol):
    def notes(self,project_id:int,limit:int|None=None)->list[Note]: ...
    def note(self,note_id:int)->Note|None: ...
    def save_note(self,project_id:int,note_id:int|None,title:str,content:str)->Note|None: ...
    def delete_note(self,note_id:int)->None: ...
    def timer(self,project_id:int|None)->TimerSummary: ...
    def toggle_timer(self,project_id:int)->TimerOutcome: ...
    def heartbeat(self,path,**kwargs)->HeartbeatOutcome: ...
